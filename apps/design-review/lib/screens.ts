export const SCREEN_IDS = SCREENS.map((screen) => screen.id);
export const SCREEN_BY_ID = Object.fromEntries(SCREENS.map((screen) => [screen.id, screen])) as Record<ScreenId, ScreenDefinition>;

export function isScreenId(value: string | null | undefined): value is ScreenId {
  return Boolean(value && SCREEN_IDS.includes(value as ScreenId));
}

export function getScreen(id: string | null | undefined): ScreenDefinition {
  return isScreenId(id) ? SCREEN_BY_ID[id] : SCREEN_BY_ID.splash;
}

